import { createHash } from "node:crypto";
import { afterAll, beforeAll, expect, it } from "vitest";
import { eq } from "drizzle-orm";
import request from "supertest";
import { login, resetDb, setTestEnv } from "./helpers";
setTestEnv();
const { createApp } = await import("../server/app");
const { getDb, closeDb } = await import("../server/db");
const { contentItems, contentRevisions, mediaAssets } = await import("../shared/schema");
let app: ReturnType<typeof createApp>;
beforeAll(async () => { await resetDb(); app = createApp(); });
afterAll(async () => { await closeDb(); });
it("guards Studio downloads against stale source revisions while retaining deliberate historical downloads", async () => {
  const db = getDb(), { agent } = await login(app);
  const [item] = await db.insert(contentItems).values({ channelId: 2, kind: "science_dialogue", title: "이전 이미지" }).returning();
  const [old] = await db.insert(contentRevisions).values({ contentItemId: item.id, revisionNo: 1, author: "operator", payload: { topic: "빛", key_question: "원래 질문" } }).returning();
  const bytes = Buffer.from("immutable-test-image");
  const [asset] = await db.insert(mediaAssets).values({ channelId: 2, contentItemId: item.id, revisionId: old.id, kind: "card", source: "studio", sha256: createHash("sha256").update(bytes).digest("hex"), bytes, mime: "image/jpeg", width: 1080, height: 1350 }).returning();
  await db.update(contentItems).set({ currentRevisionId: old.id }).where(eq(contentItems.id, item.id));
  const path = `/api/channels/2/media/${asset.id}/deck.zip`;
  expect((await request(app).get(`${path}?expectedRevision=${old.id}`)).status).toBe(401);
  expect((await agent.get(`${path}?expectedRevision=${old.id}`)).status).toBe(200);
  expect((await agent.get(`${path}?expectedRevision=bad`)).status).toBe(400);
  const [fresh] = await db.insert(contentRevisions).values({ contentItemId: item.id, revisionNo: 2, author: "operator", payload: { topic: "빛", key_question: "새 질문" } }).returning();
  await db.update(contentItems).set({ currentRevisionId: fresh.id }).where(eq(contentItems.id, item.id));
  expect((await agent.get(`${path}?expectedRevision=${old.id}`)).status).toBe(409);
  expect((await agent.get(`${path}?expectedRevision=${fresh.id}`)).status).toBe(409);
  expect((await agent.get(path)).status).toBe(200);
});
